mod field_read {
    mod values {
        pub struct Holder {
            pub value: u32,
        }
        pub fn check() -> u32 {
            super::reader::read()
            //~^ module_cycles
        }
    }
    mod factory {
        pub fn make() -> super::values::Holder {
            //~^ module_cycles
            super::values::Holder { value: 1 }
            //~^ module_cycles
        }
    }
    mod reader {
        // The field read is the only reference from `reader` to `values`.
        pub fn read() -> u32 {
            super::factory::make().value
            //~^ module_cycles
            //~| module_cycles
        }
    }
}

mod macro_written_modules {
    macro_rules! binding {
        ($name:ident) => {
            pub mod $name {
                pub fn make() -> u32 {
                    super::helper()
                }
            }
        };
    }
    binding!(first);
    fn helper() -> u32 {
        1
    }
    pub fn run() -> u32 {
        first::make()
    }
}

mod acyclic {
    mod first {
        pub mod second {
            pub(in crate::acyclic::first) struct Value;
        }
        use self::second::Value;
        fn run(_: Value) {}
    }
}

mod child_impl_of_parent {
    pub struct Parent;
    mod child {
        // Implementing a parent's type in a child module does not make the parent depend on the child.
        impl super::Parent {
            pub fn make() -> Self {
                super::Parent
            }
        }
    }
}

