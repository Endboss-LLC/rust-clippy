//@aux-build:proc_macros.rs
#![warn(clippy::module_cycles)]
#![allow(dead_code)]

extern crate proc_macros;

mod methods {
    mod values {
        pub struct Value;
    }
    mod behavior {
        // An inherent `impl` of a type from another module depends only on that module.
        impl super::values::Value {
            pub fn ping(&self) {
                super::caller::helper();
                //~^ module_cycles
            }
        }
    }
    mod caller {
        pub fn helper() {}
        pub fn run(value: super::values::Value) {
            value.ping();
            //~^ module_cycles
        }
    }
}

mod nested_generic_types {
    mod first {
        pub struct First(pub Option<Vec<std::rc::Rc<super::second::Second>>>);
        //~^ module_cycles
    }
    mod second {
        pub struct Second(pub std::marker::PhantomData<fn() -> super::first::First>);
        //~^ module_cycles
    }
}

mod macro_generated {
    // `first` counts as part of `macro_generated`, so the cycle is reported under that name.
    macro_rules! make_first {
        () => {
            mod first {
                pub fn run() {
                    super::second::run();
                    //~^ module_cycles
                }
            }
        };
    }
    make_first!();
    mod second {
        pub fn run() {
            super::first::run();
            //~^ module_cycles
        }
    }
}

mod external_macro_generated {
    // A reference in code generated by another crate's macro is reported at the macro call.
    //~v module_cycles
    proc_macros::external! {
        mod generated {
            pub fn run() {
                crate::external_macro_generated::caller::helper();
            }
        }
    }
    mod caller {
        pub fn helper() {}
        pub fn run() {
            super::generated::run();
            //~^ module_cycles
        }
    }
}

mod operators {
    mod values {
        pub struct Value;
    }
    mod impls {
        impl std::ops::Add for super::values::Value {
            type Output = Self;
            fn add(self, _: Self) -> Self {
                super::caller::helper();
                //~^ module_cycles
                self
            }
        }
    }
    mod caller {
        pub fn helper() {}
        pub fn run(left: super::values::Value, right: super::values::Value) {
            let _ = left + right;
            //~^ module_cycles
        }
    }
}

mod trait_calls {
    mod contracts {
        pub trait Action {
            fn run(&self);
        }
    }
    mod values {
        pub struct Value;
    }
    mod behavior {
        impl super::contracts::Action for super::values::Value {
            fn run(&self) {
                super::caller::helper();
                //~^ module_cycles
            }
        }
    }
    mod caller {
        use super::contracts::Action;
        pub fn helper() {}
        pub fn concrete(value: super::values::Value) {
            value.run();
            //~^ module_cycles
        }
        // Neither of these selects an implementation, so they depend only on `contracts`.
        pub fn generic<T: Action>(value: T) {
            value.run();
        }
        pub fn dynamic(value: &dyn Action) {
            value.run();
        }
        pub fn qualified(value: super::values::Value) {
            Action::run(&value);
            //~^ module_cycles
        }
    }
}

